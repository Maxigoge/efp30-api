DROP ALL OBJECTS;

CREATE TABLE media (
    id CHAR(36) PRIMARY KEY, object_key VARCHAR(80) NOT NULL UNIQUE, original_name VARCHAR(255) NOT NULL,
    mime_type VARCHAR(64) NOT NULL, size_bytes BIGINT NOT NULL, sha256 CHAR(64) NOT NULL,
    visibility VARCHAR(16) NOT NULL, enabled BOOLEAN NOT NULL DEFAULT TRUE, version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE professional_family (
    id CHAR(36) PRIMARY KEY, slug VARCHAR(100) NOT NULL UNIQUE, name VARCHAR(120) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE, sort_order INTEGER NOT NULL DEFAULT 0, version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE news (
    id CHAR(36) PRIMARY KEY, slug VARCHAR(120) NOT NULL UNIQUE, title VARCHAR(180) NOT NULL,
    summary VARCHAR(400) NOT NULL, body_markdown CLOB NOT NULL, category VARCHAR(60) NOT NULL,
    featured BOOLEAN NOT NULL DEFAULT FALSE, cover_media_id CHAR(36), status VARCHAR(16) NOT NULL,
    published_at TIMESTAMP, version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by CHAR(36), updated_by CHAR(36)
);
CREATE TABLE course (
    id CHAR(36) PRIMARY KEY, slug VARCHAR(120) NOT NULL UNIQUE, title VARCHAR(180) NOT NULL, family_id CHAR(36) NOT NULL,
    summary VARCHAR(400) NOT NULL, body_markdown CLOB NOT NULL, duration_hours INTEGER,
    modality VARCHAR(16) NOT NULL, enrollment_status VARCHAR(16) NOT NULL, cover_media_id CHAR(36),
    status VARCHAR(16) NOT NULL, published_at TIMESTAMP, version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by CHAR(36), updated_by CHAR(36)
);
CREATE TABLE course_requirement (
    course_id CHAR(36) NOT NULL, position SMALLINT NOT NULL, requirement VARCHAR(240) NOT NULL,
    PRIMARY KEY (course_id, position)
);
CREATE TABLE course_photo (
    id CHAR(36) PRIMARY KEY, course_id CHAR(36) NOT NULL, media_id CHAR(36) NOT NULL, alt VARCHAR(240) NOT NULL,
    position SMALLINT NOT NULL, enabled BOOLEAN NOT NULL DEFAULT TRUE, show_on_homepage BOOLEAN NOT NULL DEFAULT FALSE,
    UNIQUE (course_id, position)
);
CREATE TABLE calendar_event (
    id CHAR(36) PRIMARY KEY, slug VARCHAR(120) NOT NULL UNIQUE, title VARCHAR(180) NOT NULL,
    description CLOB NOT NULL, starts_at TIMESTAMP NOT NULL, ends_at TIMESTAMP NOT NULL, timezone VARCHAR(64) NOT NULL,
    location VARCHAR(240) NOT NULL, all_day BOOLEAN NOT NULL DEFAULT FALSE, status VARCHAR(16) NOT NULL,
    published_at TIMESTAMP, version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by CHAR(36), updated_by CHAR(36)
);
CREATE TABLE institution (
    id SMALLINT PRIMARY KEY, name VARCHAR(180) NOT NULL, description VARCHAR(4000) NOT NULL,
    address VARCHAR(240) NOT NULL, email VARCHAR(254) NOT NULL, phones CLOB NOT NULL,
    social_links CLOB NOT NULL, version BIGINT NOT NULL DEFAULT 0,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_by CHAR(36)
);
CREATE TABLE admin_user (
    id CHAR(36) PRIMARY KEY, display_name VARCHAR(120) NOT NULL, email VARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL, enabled BOOLEAN NOT NULL DEFAULT TRUE, version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE admin_user_role (user_id CHAR(36) NOT NULL, role VARCHAR(16) NOT NULL, PRIMARY KEY (user_id, role));
CREATE TABLE SPRING_SESSION (
    PRIMARY_ID CHAR(36) NOT NULL PRIMARY KEY, SESSION_ID CHAR(36) NOT NULL UNIQUE,
    CREATION_TIME BIGINT NOT NULL, LAST_ACCESS_TIME BIGINT NOT NULL, MAX_INACTIVE_INTERVAL INTEGER NOT NULL,
    EXPIRY_TIME BIGINT NOT NULL, PRINCIPAL_NAME VARCHAR(100)
);
CREATE INDEX SPRING_SESSION_IX2 ON SPRING_SESSION (EXPIRY_TIME);
CREATE INDEX SPRING_SESSION_IX3 ON SPRING_SESSION (PRINCIPAL_NAME);
CREATE TABLE SPRING_SESSION_ATTRIBUTES (
    SESSION_PRIMARY_ID CHAR(36) NOT NULL, ATTRIBUTE_NAME VARCHAR(200) NOT NULL, ATTRIBUTE_BYTES BLOB NOT NULL,
    PRIMARY KEY (SESSION_PRIMARY_ID, ATTRIBUTE_NAME),
    CONSTRAINT SPRING_SESSION_ATTRIBUTES_FK FOREIGN KEY (SESSION_PRIMARY_ID) REFERENCES SPRING_SESSION(PRIMARY_ID) ON DELETE CASCADE
);
